"""大脑的系统提示词：① 固定的规则（身份底线、怎么用工具、光遇常识）② 人设和记忆（开新记录时重读）。"""

from __future__ import annotations

from ..chat.memory import MemoryStore
from ..chat.responder import identity_sections
